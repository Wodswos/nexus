import { test, expect } from '@playwright/test';
import { account, choose, config, environmentRoutes, tasks, workspace } from '../workspace-fixture';

test.use({ serviceWorkers: 'block', viewport: { width: 1440, height: 1000 } });

test('Settings manages Kubernetes clusters and Task details manage inherited templates without a default selector', async ({ page, context }, testInfo) => {
  await account(context);
  await page.goto('/settings');
  await page.getByRole('button', { name: '添加 Kubernetes 集群', exact: true }).click();
  await page.getByLabel('Kubernetes 连接名称', { exact: true }).fill('开发集群');
  await page.getByLabel('Kubernetes API Server', { exact: true }).fill('https://cluster.example.invalid:6443');
  await page.getByLabel('Kubernetes 默认 Namespace', { exact: true }).fill('agent-team');
  await page.getByLabel('Kubernetes 访问 Token', { exact: true }).fill('temporary-fixture-token');
  await page.getByRole('button', { name: '保存连接', exact: true }).click();
  await expect(page.getByRole('button', { name: '编辑 开发集群', exact: true })).toBeVisible();
  const connections = (await (await context.request.get('/api/kubernetes-connections')).json()).data;
  expect(connections).toHaveLength(1);
  expect(connections[0]).toMatchObject({ namespace: 'agent-team', tokenSet: true });
  expect(JSON.stringify(connections)).not.toContain('temporary-fixture-token');
  await page.getByRole('button', { name: '编辑 开发集群', exact: true }).click();
  await expect(page.getByLabel('Kubernetes 访问 Token', { exact: true })).toHaveValue('');
  await page.getByLabel('Kubernetes 连接名称', { exact: true }).fill('开发集群 v2');
  await page.getByRole('button', { name: '保存连接', exact: true }).click();
  await expect(page.getByRole('button', { name: '编辑 开发集群 v2', exact: true })).toBeVisible();
  await page.locator('input[type=file]').setInputFiles({ name: 'tasks.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ tasks })) });
  await expect(page.getByText(/已合并备份/)).toBeVisible();
  await page.goto('/tasks?project=agent-project&view=mindmap&scope=all');
  await page.locator('.react-flow__node[data-id="agent-project"] [data-mind-title]').click();
  const section = workspace(page);
  await expect(section.getByText('暂无 Workspace', { exact: true })).toBeVisible();
  await expect(section.getByRole('heading', { name: '已创建 Workspace', exact: true })).toHaveCount(0);
  await section.getByRole('button', { name: '创建 Workspace 模板', exact: true }).click();
  const create = page.getByRole('dialog', { name: '创建 Workspace 模板', exact: true });
  await create.getByLabel('Workspace 模板名称', { exact: true }).fill('项目 Pod 模板');
  await choose(page, create, '运行方式', 'Kubernetes Pod');
  await choose(page, create, 'Kubernetes 连接方式', '直接连接 Kubernetes API');
  await choose(page, create, 'Kubernetes API 连接', '开发集群 v2');
  await expect(create.getByLabel('Namespace', { exact: true })).toHaveValue('agent-team');
  await create.getByLabel('Image', { exact: true }).fill('node:24');
  await create.getByRole('button', { name: '保存配置', exact: true }).click();
  await expect(create).toHaveCount(0);
  await page.goto('/tasks?project=agent-project&view=mindmap&scope=all');
  await page.locator('.react-flow__node[data-id="agent-task"] [data-mind-title]').click();
  const templates = section.locator('details[aria-label="可用 Workspace 模板"]');
  await expect(templates).not.toHaveAttribute('open', '');
  await templates.locator('summary').click();
  await expect(templates).toContainText('Agent 项目');
  await templates.getByRole('button', { name: /项目 Pod 模板/ }).click();
  const edit = page.getByRole('dialog', { name: '编辑 Workspace 模板', exact: true });
  await expect(edit.getByLabel('Namespace', { exact: true })).toHaveValue('agent-team');
  await edit.getByLabel('Workspace 模板名称', { exact: true }).fill('项目 Pod 模板 · 已编辑');
  await edit.getByLabel('Namespace', { exact: true }).fill('custom-team');
  await edit.getByRole('button', { name: '保存配置', exact: true }).click();
  await expect(edit).toHaveCount(0);
  await templates.getByRole('button', { name: /项目 Pod 模板 · 已编辑/ }).click();
  await expect(edit.getByLabel('Namespace', { exact: true })).toHaveValue('custom-team');
  await edit.getByRole('button', { name: '取消', exact: true }).click();
  await section.scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('workspace-templates.png') });
  await templates.getByRole('button', { name: /项目 Pod 模板 · 已编辑/ }).click();
  await edit.getByRole('button', { name: '删除此 Workspace 模板', exact: true }).click();
  await edit.getByRole('button', { name: '确认删除 Workspace 模板', exact: true }).click();
  await expect(edit).toHaveCount(0);
  await expect(templates).toContainText('暂无可用模板');
  await page.goto('/settings');
  await page.getByRole('button', { name: '编辑 开发集群 v2', exact: true }).click();
  await page.getByRole('button', { name: '删除连接', exact: true }).click();
  await page.getByRole('button', { name: '确认删除连接', exact: true }).click();
  await expect(page.getByText('暂无 Kubernetes 集群', { exact: true })).toBeVisible();
});

test('empty existing-Workspace tab cannot accidentally launch a new Workspace', async ({ page, context }) => {
  await account(context);
  await environmentRoutes(page, []);
  await page.route('**/api/tasks/*/agents', route => route.fulfill({ json: { data: [] } }));
  await page.goto('/settings');
  await page.locator('input[type=file]').setInputFiles({ name: 'tasks.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ tasks })) });
  await expect(page.getByText(/已合并备份/)).toBeVisible();
  await page.goto('/tasks?project=agent-project&view=mindmap&scope=all');
  await page.locator('.react-flow__node[data-id="agent-task"] [data-mind-title]').click();
  await workspace(page).getByRole('button', { name: '创建 Agent', exact: true }).click();
  const create = page.getByRole('dialog', { name: '创建 Agent', exact: true });
  await create.getByRole('tab', { name: '使用已有 Workspace', exact: true }).click();
  await expect(create.getByText('暂无可用 Workspace', { exact: true })).toBeVisible();
  await expect(create.getByRole('combobox', { name: 'Agent Workspace 模板', exact: true })).toHaveCount(0);
  await expect(create.locator('button[type=submit]')).toBeDisabled();
  await create.getByRole('tab', { name: '从模板创建新 Workspace', exact: true }).click();
  await expect(create.getByRole('combobox', { name: 'Agent Workspace 模板', exact: true })).toBeVisible();
});


test('new Workspace preview resolves a complete path and submission keeps the preview identity', async ({ page, context }) => {
  await account(context);
  expect((await context.request.put('/api/servers/agent-host', { data: { name: 'Fixture host', host: 'fixture@host.invalid' } })).ok()).toBe(true);
  const settings = { ...config, runtime: 'docker', image: 'node:24', workRoot: '/srv/nexus', repository: 'https://github.com/example/project.git' };
  await page.goto('/settings');
  await page.locator('input[type=file]').setInputFiles({ name: 'preview.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ tasks, workspaces: [{ id: 'agent-project', mode: 'override', ...settings }] })) });
  await expect(page.getByText(/已合并备份/)).toBeVisible();
  await page.goto('/tasks?project=agent-project&view=mindmap&scope=all');
  await page.locator('.react-flow__node[data-id="agent-task"] [data-mind-title]').click();
  await workspace(page).getByRole('button', { name: '创建 Agent', exact: true }).click();
  const create = page.getByRole('dialog', { name: '创建 Agent', exact: true });
  const previewResponse = page.waitForResponse(response => response.url().endsWith('/preview') && response.request().postDataJSON().worktreeName === 'edited-task-123');
  await create.getByLabel('Worktree 名称', { exact: true }).fill('edited-task-123');
  const response = await previewResponse;
  expect(response.ok()).toBe(true);
  const preview = (await response.json()).data, previewRequest = response.request().postDataJSON();
  expect(preview.directory).toBe(`/srv/nexus/${preview.environmentId}/nexus-agent/edited-task-123`);
  await expect(create.getByRole('group', { name: 'Agent 工作目录配置' })).toContainText(`路径：${preview.directory}`);
  expect((await (await context.request.get('/api/workspace-environments')).json()).data).toHaveLength(0);
  let submitted: any;
  await page.route('**/api/tasks/*/workspace-launch', route => {
    submitted = route.request().postDataJSON();
    return route.fulfill({ status: 502, json: { error: '仅测试提交边界，不创建远端资源' } });
  });
  await create.getByRole('button', { name: '创建 Workspace 与 Agent', exact: true }).click();
  await expect(create.getByRole('alert')).toContainText('仅测试提交边界');
  expect(submitted.requestId).toBe(previewRequest.requestId);
  expect(submitted.config).toEqual(previewRequest.config);
  expect(submitted.agent).toMatchObject({ worktreeName: 'edited-task-123', worktree: true });
  expect(submitted.agent.round).toBeUndefined();
});
