import { test, expect } from '@playwright/test';

test.use({ serviceWorkers: 'block', viewport: { width: 1280, height: 900 } });
test('reads long Markdown, searches, compares revisions and restores without losing history', async ({ page, context }, testInfo) => {
  const invite = await context.request.post('/api/invites', { headers: { Cookie: process.env.E2E_ADMIN_COOKIE! }, data: {} }).then(response => response.json());
  expect((await context.request.post('/api/auth/register', { data: { username: `doc_${Date.now()}`, password: 'fixture-password', inviteCode: invite.code } })).ok()).toBeTruthy();
  const token = await context.request.post('/api/tokens', { data: { name: 'document fixture', permission: 'write', expiresInDays: 1 } }).then(response => response.json());
  const headers = { Authorization: `Bearer ${token.token}` };
  const project = await context.request.post('/api/v1/projects', { headers, data: { title: '正文版本项目' } }).then(response => response.json());
  const original = '# 需求说明\n\n原始人工要求。\n\n## 验收标准\n\n保留全部历史版本。';
  const created = await context.request.post('/api/v1/tasks', { headers, data: { title: '任务正文阅读', parentId: project.data.id, status: 'todo', notes: original } }).then(response => response.json());
  const taskId = created.data.id;
  const initialResponse = await context.request.get(`/api/v1/tasks/${taskId}/description`, { headers });
  expect(initialResponse.status()).toBe(200);
  const initial = await initialResponse.json();
  const longText = original + '\n\n## 执行方案\n\n' + '这是最新的中文方案内容，需要保留并可以查阅。\n\n'.repeat(80) + '\n<script>alert("unsafe")</script>';
  expect((await context.request.patch(`/api/v1/tasks/${taskId}/description`, { headers, data: { expectedRevisionId: initial.data.id, notes: longText } })).ok()).toBeTruthy();
  await page.goto(`/tasks?project=${project.data.id}&view=mindmap&scope=all`);
  await page.locator(`.react-flow__node[data-id="${taskId}"] [data-mind-title]`).click();
  await page.getByRole('button', { name: '展开阅读全文', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '任务正文阅读', exact: true });
  await expect(dialog.getByRole('heading', { name: '需求说明' })).toBeVisible();
  await dialog.getByLabel('搜索正文').fill('最新的中文方案');
  await expect(dialog.getByText('80 条匹配')).toBeVisible();
  await dialog.getByLabel('搜索正文').fill('');
  await dialog.getByRole('button', { name: '历史版本', exact: true }).click();
  const rows = dialog.getByLabel('版本列表').getByRole('button');
  await expect(rows).toHaveCount(2);
  await rows.nth(1).click();
  await expect(dialog.getByText('− 所选版本移除的内容　＋ 比较目标新增的内容')).toBeVisible();
  await dialog.getByRole('button', { name: '恢复此版本', exact: true }).click();
  await dialog.getByRole('button', { name: '确认恢复', exact: true }).click();
  await expect(rows).toHaveCount(3);
  const current = await context.request.get(`/api/v1/tasks/${taskId}/description`, { headers }).then(response => response.json());
  expect(current.data.notes).toBe(original); expect(current.data.source).toBe('restore');
  await dialog.getByRole('button', { name: '阅读', exact: true }).click();
  await expect(dialog.getByText('原始人工要求。', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(dialog).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('task-document-mobile.png'), animations: 'disabled' });
});
